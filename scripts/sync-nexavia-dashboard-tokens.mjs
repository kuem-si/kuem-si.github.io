#!/usr/bin/env node
// Writes src/styles/nexavia-dashboard-tokens.css from a nexavia-brand-assets
// checkout: the Nexavia Enterprise colour tokens (light, dark and both
// high-contrast modes), re-scoped from :root to the showroom's simulated
// dashboard screen (.xdr-screen). The values are copied, never edited; the
// header names the release tag, its commit and the source file's SHA-256,
// which must match the checksum in that release's release.json.
//
//   node scripts/sync-nexavia-dashboard-tokens.mjs <nexavia-brand-assets checkout>
//   node scripts/sync-nexavia-dashboard-tokens.mjs <checkout> --check
//
// The checkout must be at a release tag (git describe --exact-match).
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src/styles/nexavia-dashboard-tokens.css");
const SOURCE = "tokens/nexavia.tokens.css";
const SCOPE = ".xdr-screen";
const DARK = '.xdr-screen[data-scheme="carbon"]';
const BLOCKS = {
  light:
    ':root[data-nx-member="enterprise"], :root[data-nx-member="enterprise"][data-nx-theme="light"]',
  dark: ':root[data-nx-member="enterprise"][data-nx-theme="dark"]',
  hcLight:
    ':root[data-nx-member="enterprise"][data-nx-contrast="more"]:not([data-nx-theme="dark"])',
  hcDark:
    ':root[data-nx-member="enterprise"][data-nx-contrast="more"][data-nx-theme="dark"]',
};

const [dir, flag] = process.argv.slice(2);
if (!dir) {
  console.error(
    "usage: node scripts/sync-nexavia-dashboard-tokens.mjs <nexavia-brand-assets checkout> [--check]",
  );
  process.exit(2);
}
const git = (...args) =>
  execFileSync("git", ["-C", dir, ...args], { encoding: "utf8" }).trim();
const tag = git("describe", "--tags", "--exact-match", "HEAD");
const commit = git("rev-parse", "HEAD");
const bytes = readFileSync(join(dir, SOURCE));
const sha = createHash("sha256").update(bytes).digest("hex");
const release = JSON.parse(readFileSync(join(dir, "release.json"), "utf8"));
const listed = release.outputs.find((o) => o.path === SOURCE);
if (release.tag !== tag || !listed || listed.sha256 !== sha) {
  console.error(
    `${SOURCE} at ${tag} does not match release.json (tag ${release.tag})`,
  );
  process.exit(1);
}

const css = bytes.toString("utf8");
function block(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0 || css.indexOf(`${selector} {`, start + 1) >= 0)
    throw new Error(`expected one block for ${selector}`);
  const body = css.slice(start + selector.length + 2, css.indexOf("}", start));
  const decls = body
    .split("\n")
    .map((l) => l.trim())
    .filter(
      (l) =>
        /^--nx-(color|member)-[a-z0-9-]+: [^;]+;$/.test(l) ||
        /^color-scheme: (light|dark);$/.test(l),
    );
  if (decls.length < 20)
    throw new Error(`too few colour tokens in ${selector}`);
  return decls;
}
const rule = (selector, decls, indent = "") =>
  `${indent}${selector} {\n${decls.map((d) => `${indent}  ${d}`).join("\n")}\n${indent}}\n`;

const out = [
  "/*",
  ` * Generated by scripts/sync-nexavia-dashboard-tokens.mjs from kuem-si/nexavia-brand-assets ${SOURCE}`,
  ` * (release ${tag} @${commit}, sha256 ${sha}).`,
  " * Nexavia Enterprise colour tokens, re-scoped from :root to the showroom's simulated",
  ' * dashboard screen. data-scheme="carbon" on the screen selects the dark values.',
  " * Do not edit: run the script again against a newer nexavia-brand-assets release tag.",
  " */",
  rule(SCOPE, block(BLOCKS.light)),
  rule(DARK, block(BLOCKS.dark)),
  "@media (prefers-contrast: more) {",
  rule(SCOPE, block(BLOCKS.hcLight), "  ") +
    rule(DARK, block(BLOCKS.hcDark), "  ") +
    "}",
  "",
].join("\n");

if (flag === "--check") {
  const current = readFileSync(OUT, "utf8");
  if (current !== out) {
    console.error(
      "src/styles/nexavia-dashboard-tokens.css is out of date or was edited by hand",
    );
    process.exit(1);
  }
  console.log(
    `nexavia-dashboard-tokens.css matches ${tag} @${commit.slice(0, 7)}`,
  );
} else {
  writeFileSync(OUT, out);
  console.log(
    `wrote src/styles/nexavia-dashboard-tokens.css from ${tag} @${commit.slice(0, 7)}`,
  );
}
